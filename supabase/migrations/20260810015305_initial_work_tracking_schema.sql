create index idx_feed_events_created_at on public.feed_events(created_at desc);

create view public.v_today_task_summary with (security_invoker = true) as
select
  work_date,
  count(*)::integer as total_tasks,
  count(*) filter (where status = 'todo')::integer as todo_tasks,
  count(*) filter (where status = 'doing')::integer as doing_tasks,
  count(*) filter (where status = 'done')::integer as done_tasks,
  count(*) filter (where priority = 'high' and status <> 'done')::integer as open_high_priority_tasks,
  count(*) filter (where due_date < work_date and status <> 'done')::integer as overdue_tasks
from public.tasks
group by work_date;

create view public.v_github_repo_dashboard with (security_invoker = true) as
select
  s.owner_name,
  s.repo_name,
  s.repo_url,
  s.default_branch,
  s.latest_commit_sha,
  s.latest_commit_at,
  s.open_pr_count,
  count(e.commit_sha)::integer as tracked_commit_events
from public.github_repo_snapshots as s
left join public.github_commit_events as e
  on e.owner_name = s.owner_name and e.repo_name = s.repo_name
group by
  s.owner_name, s.repo_name, s.repo_url, s.default_branch,
  s.latest_commit_sha, s.latest_commit_at, s.open_pr_count;

insert into storage.buckets (id, name, public)
values ('work-tracking-private', 'work-tracking-private', false)
on conflict (id) do update set public = false;

revoke all on table
  public.app_settings,
  public.work_days,
  public.tasks,
  public.task_assignees,
  public.focus_sessions,
  public.notion_sync_runs,
  public.notion_pages_snapshot,
  public.notion_update_events,
  public.github_sync_runs,
  public.github_repo_snapshots,
  public.github_pull_request_snapshots,
  public.github_commit_events,
  public.github_pr_events,
  public.auth_sessions,
  public.auth_oauth_states,
  public.line_works_messages,
  public.line_works_attachments,
  public.line_works_links,
  public.line_works_link_previews,
  public.line_works_channels,
  public.user_last_seen,
  public.user_notion_read,
  public.users,
  public.task_references,
  public.site_links,
  public.site_link_categories,
  public.feed_events,
  public.v_today_task_summary,
  public.v_github_repo_dashboard
from anon, authenticated;

revoke all on sequence
  public.notion_sync_runs_id_seq,
  public.github_sync_runs_id_seq,
  public.line_works_attachments_id_seq,
  public.line_works_links_id_seq,
  public.task_references_id_seq,
  public.site_links_id_seq,
  public.feed_events_id_seq
from anon, authenticated;

do $$
declare
  target record;
begin
  for target in
    select schemaname, tablename
    from pg_tables
    where schemaname = 'public'
      and tablename in (
        'app_settings', 'work_days', 'tasks', 'task_assignees', 'focus_sessions',
        'notion_sync_runs', 'notion_pages_snapshot', 'notion_update_events',
        'github_sync_runs', 'github_repo_snapshots', 'github_pull_request_snapshots',
        'github_commit_events', 'github_pr_events', 'auth_sessions', 'auth_oauth_states',
        'line_works_messages', 'line_works_attachments', 'line_works_links',
        'line_works_link_previews', 'line_works_channels', 'user_last_seen',
        'user_notion_read', 'users', 'task_references', 'site_links',
        'site_link_categories', 'feed_events'
      )
  loop
    execute format('alter table %I.%I enable row level security', target.schemaname, target.tablename);
  end loop;
end;
$$;

commit;
