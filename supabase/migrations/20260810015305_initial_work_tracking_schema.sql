);

create index idx_line_works_links_message on public.line_works_links(message_id);

create table public.line_works_link_previews (
  url text primary key,
  title text,
  description text,
  image_url text,
  site_name text,
  status text not null default 'success' check (status in ('success', 'failed')),
  error_message text,
  fetched_at timestamptz not null default now()
);

create index idx_line_works_link_previews_fetched on public.line_works_link_previews(fetched_at desc);

create table public.line_works_channels (
  channel_id text primary key,
  title text,
  channel_type text,
  user_id text,
  last_fetched_at timestamptz
);

create table public.user_last_seen (
  user_id text not null,
